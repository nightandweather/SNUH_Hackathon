const assert = require('node:assert/strict');
const r = require('../static/replay-observations.js');
const row = (minute,vitals={},age=Object.fromEntries(Object.keys(vitals).map(k=>[k,0]))) => ({minute,vitals,age});
const historical = (minute,value,extra={}) => ({historical_only:true,table:'CHARTEVENTS',variable:'hr',unit:'bpm',chart_minute:minute,value,...extra});
const source = {id:'CASE-1',rows:[row(0,{hr:80,map:70}),row(10,{hr:80},{hr:10}),row(20,{hr:100,map:60}),row(90)]};
const pristine=JSON.stringify(source);
assert.equal(r.numericAt(source,'hr',0).kind,'measured');
assert.equal(r.numericAt(source,'hr',0).value,80);
assert.equal(r.numericAt(source,'hr',10).kind,'carried');
assert.equal(r.numericAt(source,'hr',10).observedMinute,0,'age reconstructs actual observation timestamp');
assert.equal(r.collectSeries(source,'hr').length,2,'carried repeats deduplicate');
const estimate=r.numericAt(source,'hr',10,{interpolate:true});
assert.equal(estimate.value,90);assert.equal(estimate.kind,'interpolated');assert.equal(estimate.usesFutureObservation,true);
assert.deepEqual(estimate.endpointMinutes,[0,20]);assert.deepEqual(estimate.endpointValues,[80,100]);
assert.equal(estimate.forDisplayOnly,true);assert.equal(r.numericAt(source,'map',10,{interpolate:true}).value,65);
assert.equal(r.numericAt(source,'hr',20,{interpolate:true}).kind,'measured','exact observation never replaced with estimate');
assert.equal(r.numericAt(source,'hr',80,{interpolate:true}).kind,'carried','no extrapolation beyond last measurement');
assert.equal(r.numericAt(source,'hr',80).age,60,'old observation retained with real age');
assert.equal(r.numericAt(source,'hr',-1,{interpolate:true}).value,null);
assert.equal(r.numericAt(source,'hr',91,{interpolate:true}).reason,'outside-source-range');
assert.equal(r.numericAt(source,'bad-key',10).value,null);
assert.equal(r.numericAt(source,'hr',NaN).value,null);
assert.equal(r.numericAt(null,'hr',0).value,null);
const sparse={rows:[row(0),row(20,{hr:80}),row(100,{hr:100})]};
assert.equal(r.numericAt(sparse,'hr',10,{interpolate:true}).reason,'before-first-observation','no backfill from future');
assert.equal(r.numericAt(sparse,'hr',60,{interpolate:true}).kind,'carried','gap over 60 minutes never interpolated');
assert.equal(r.numericAt(sparse,'hr',60,{interpolate:true}).reason,'gap-too-wide');
const sixty={rows:[row(0,{hr:80}),row(60,{hr:100})]};
assert.equal(r.numericAt(sixty,'hr',30,{interpolate:true}).value,90,'inclusive 60-minute display gap');
const retrospective={rows:[row(0),row(10),row(20)],historical_vital_observations:[historical(0,90),historical(20,110)]};
assert.equal(r.numericAt(retrospective,'hr',10,{interpolate:true}).value,100);
assert.equal(r.numericAt(retrospective,'hr',10,{interpolate:true}).historical,true);
const duplicate={...source,historical_vital_observations:[historical(0,80)]};
assert.equal(r.numericAt(duplicate,'hr',0).kind,'measured');
const conflict={...source,historical_vital_observations:[historical(0,120)]};
assert.equal(r.numericAt(conflict,'hr',0).kind,'conflict');
assert.equal(r.numericAt(conflict,'hr',10,{interpolate:true}).kind,'conflict','cannot bridge a prior conflict');
assert.equal(r.numericAt(conflict,'hr',20).kind,'measured','later unambiguous source supersedes conflict');
const explicitConflict={...source,historical_vital_observations:[historical(20,100,{same_time_conflict:true})]};
assert.equal(r.numericAt(explicitConflict,'hr',10,{interpolate:true}).kind,'carried','cannot bridge a future conflict');
assert.equal(r.numericAt(explicitConflict,'hr',20).kind,'conflict');
const invalidHistorical={...source,historical_vital_observations:[historical(0,500,{unit:'mmHg'}),historical(0,500,{table:'LABEVENTS'}),historical(0,500,{historical_only:false}),historical(0,500,{chart_minute:-1}),historical(0,'500')]};
assert.equal(r.numericAt(invalidHistorical,'hr',0).value,80,'only numeric reviewed historical units and source accepted');
const invalidRows={rows:[row(0,{hr:null}),row(10,{hr:100},{hr:-1}),row(20,{hr:Infinity}),row(30,{hr:50},{hr:undefined})]};
assert.equal(r.numericAt(invalidRows,'hr',20).value,null,'invalid numeric data or missing ages never manufacture values');
const beyondRange={rows:[row(0),row(20)],historical_vital_observations:[historical(10,100),historical(30,110)]};
assert.equal(r.numericAt(beyondRange,'hr',20,{interpolate:true}).kind,'carried','no interpolation using endpoint outside source replay range');
assert.equal(JSON.stringify(source),pristine,'source not modified by reading, interpolation or deduplication');
const slots=[{case:source,minute:10,caseIndex:0,label:'P001',status:{key:'red',label:'RED'},lab:{label:'Hemoglobin',value:12,unit:'g/dL',minute:5}},null,{status:{key:'yellow',label:'예약'}}];
const html=r.renderTable({slots,interpolate:true,includeLab:true});
assert.equal((html.match(/data-replay-bed=/g)||[]).length,8,'always eight bed rows');
assert.match(html,/data-case="0"/);assert.match(html,/data-state="yellow"/);assert.match(html,/보간 추정/);assert.match(html,/≈ 90/);assert.match(html,/Hemoglobin/);
assert.match(html,/data-replay-interpolate checked/);assert.match(html,/AI·알림·의료진 이동 판단에는 사용하지 않습니다/);
assert.doesNotMatch(html,/undefined|NaN|Infinity/);
const english=r.renderTable({slots,lang:'en',interpolate:false});
assert.match(english,/Eight-bed observation summary/);assert.match(english,/10 min since observation/);assert.doesNotMatch(english,/≈ 90/);
const injection=r.renderTable({slots:[{case:source,minute:10,label:'<script>boom</script>',status:{key:'red',label:'<img onerror="boom">'}}]});
assert.doesNotMatch(injection,/<script>|<img onerror/);assert.match(injection,/&lt;script&gt;/);
const futureLab=r.renderTable({slots:[{case:source,minute:10,lab:{label:'FUTURE-LAB',value:100,minute:11}}],includeLab:true});
assert.doesNotMatch(futureLab,/FUTURE-LAB/,'future lab summary never leaked into selected time');
console.log('PASS: exact vs carried vs interpolated values, true source timestamps, bounded gaps, conflicts, no extrapolation, readonly inputs, 8-bed markup, escaping and time-safe lab summaries.');

