const assert=require('node:assert/strict');
const planner=require('../static/record-visit-planner.js');
const row=(minute,vitals,age=Object.fromEntries(Object.keys(vitals).map(k=>[k,0])))=>({minute,vitals,age});
const old=row(0,{hr:80,map:70});
const freshSame=row(10,{hr:80,map:70});
const carried=row(10,{hr:80,map:70},{hr:10,map:10});
let beds=[{index:0,current:carried,previous:old},{index:5,current:freshSame,previous:old}];
assert.equal(planner.plan({beds}).bedIndex,5,'new source observations outrank carried values');
assert.equal(planner.plan({beds}).newObservationCount,2);
assert.equal(planner.plan({beds}).changedVariableCount,0,'new observations need not change');
const fullValues={hr:80,map:70,spo2:96,rr:18,sbp:110};
const rankedChange=planner.plan({beds:[{index:0,current:row(10,fullValues),previous:row(0,fullValues)},
 {index:4,current:row(10,{hr:100}),previous:row(0,{hr:80})}]});
assert.equal(rankedChange.bedIndex,4,'an actual value change outranks more unchanged new measurements');
assert.equal(rankedChange.method,'changed-observation');
const before=JSON.stringify(beds);planner.plan({beds});assert.equal(JSON.stringify(beds),before,'does not mutate source rows');
beds=[{index:1,current:row(10,{hr:81,map:70}),previous:old},{index:6,current:row(10,{hr:100,map:60}),previous:old}];
assert.equal(planner.plan({beds}).bedIndex,6,'changed variable count breaks new-observation tie');
beds=[{index:1,current:row(10,{hr:82}),previous:row(0,{hr:80})},{index:6,current:row(10,{hr:100}),previous:row(0,{hr:80})}];
assert.equal(planner.plan({beds}).bedIndex,6,'relative change breaks otherwise equal rank');
beds[0].hasExistingAlert=true;assert.equal(planner.plan({beds}).bedIndex,1,'only explicit existing alert takes priority');
assert.equal(planner.plan({beds}).method,'existing-alert');
const invalid=row(10,{hr:null,map:NaN,spo2:false,rr:Infinity,sbp:0},{hr:0,map:0,spo2:0,rr:0,sbp:31});
assert.deepEqual(planner.observations(invalid),{},'missing, nonnumeric, and expired values do not become observations');
assert.deepEqual(planner.observations(row(1,{hr:80},{hr:2})),{},'pre-admission observation is not valid');
beds=[{index:0,current:carried,previous:old},{index:5,current:carried,previous:old}];
assert.equal(planner.plan({beds,fallbackIndex:4}).bedIndex,5);
assert.equal(planner.plan({beds,fallbackIndex:4}).method,'scheduled');
assert.match(planner.plan({beds}).reason_en,/Scheduled rounding/);
const correction=[{index:3,current:row(10,{hr:90},{hr:10}),previous:row(0,{hr:80})}];
assert.equal(planner.plan({beds:correction}).method,'changed-observation','same-time correction is not called a new observation');
assert.equal(planner.plan({beds:correction}).newObservationCount,0);
const older=[{index:3,current:row(10,{hr:90},{hr:10}),previous:row(10,{hr:80})}];
assert.equal(planner.plan({beds:older}).method,'scheduled','older observation is not treated as newly changed evidence');
assert.equal(planner.plan().bedIndex,null);
const n=planner.plan({beds:correction,phase:'nurse'}),d=planner.plan({beds:correction,phase:'doctor'});
assert.equal(n.bedIndex,d.bedIndex,'N and Dr receive identical rank for the same source comparison');
assert.equal(d.clinicalSeverityAssessed,false);
assert.equal(d.staffMovementSimulated,true);
assert.match(d.reason_en,/Dr\. record review/);
console.log('PASS: source timestamp ranking, changes and tie-breaking, explicit alert priority, missing data, fallback, input immutability and N/Dr pair consistency.');
